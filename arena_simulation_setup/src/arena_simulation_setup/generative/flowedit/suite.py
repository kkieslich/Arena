"""`flowedit suite`: a split as an arena_evaluation benchmark suite whose runs pair by seed."""

from __future__ import annotations

import re
import shlex
from collections.abc import Callable, Iterable, Mapping, Sequence
from pathlib import Path
from typing import Any

from .split import BASE_CROWD, PARTITIONS, base_of, duration_of, is_base, jobs, regenerate_worlds, robot_task_of

#: The stage name's seed suffix: `<world>__s<seed>`
STAGE_SEP = "__s"
_STAGE_RE = re.compile(rf"^(?P<world>.+){re.escape(STAGE_SEP)}(?P<seed>\d+)$")
#: Where the idle robot parks, the runner's own parking spot for its `unhindered_peds` reference runs: off any map
PARK = 1000.0
#: The robot every stage spawns, parked and unseen without a robot task. Jackal is the robot of every shipped suite.
ROBOT = "jackal"
#: The contestant of a crowd-only run: the parked robot comes up with the no-op mobile adapter (`robot.mobile:=none`),
#: not the sim's default navstack (Nav2 in flatsim, ~12 % of a core and ~0.4 GB per lane for a robot that never moves)
CONTEST = "[{name: peds_only, mobile: none}]"
#: Launch args of the whole run: lockstep for runs that pair by seed, people blind to the parked robot
LAUNCH = {"sim": "flatsim", "headless": "true", "lockstep": "true", "human.robots.visible": "false"}
#: Launch args of a run whose robot drives the split's robot task: the people see it
LAUNCH_TASK = {**LAUNCH, "human.robots.visible": "true"}
#: First line of every suite and contest this writes, so it never replaces one it did not write
MARKER = "# generated by flowedit suite"
SUITES = "suites"
CONTESTS = "contests"


def stage_name(world: str, seed: int) -> str:
    """`<world>__s<seed>`: the stage of `world` at `seed`."""
    if _STAGE_RE.match(world):
        raise ValueError(f"{world}: a world name ending in {STAGE_SEP}<digits> would not parse back from its stage name")
    return f"{world}{STAGE_SEP}{int(seed)}"


def parse_stage_name(name: str) -> tuple[str, int]:
    """`(world, seed)` of a stage name `stage_name` wrote; ValueError for any other name."""
    m = _STAGE_RE.match(name)
    if m is None:
        raise ValueError(f"{name!r} is no flowedit stage name (<world>{STAGE_SEP}<seed>)")
    return m["world"], int(m["seed"])


def stage(world: str, seed: int, scenario: str, duration: float, robot: str = ROBOT, *, task: bool = False) -> dict[str, Any]:
    """The stage that runs `scenario` in `world` for one episode of `duration` sim seconds at episode seed `seed`: the
    robot parked off the map, or driving the robot task `scenario` carries when `task`."""
    if task:
        modes, config = {"robots": "scenario", "obstacles": "scenario"}, {"scenario": {"file": scenario}}
    else:
        modes, config = {"robots": "stationary", "obstacles": "scenario"}, {"scenario": {"file": scenario}, "stationary": {"pos_x": PARK, "pos_y": PARK}}
    return {"name": stage_name(world, seed), "map": world, "robot": robot, "modes": modes, "episodes": 1, "seed": int(seed), "timeout": float(duration), "config": config}


def suite_doc(stages: Sequence[Mapping[str, Any]], launch: Mapping[str, str] | None = None) -> dict[str, Any]:
    """The suite of `stages` without the runner's reference steps; ValueError for a stage listed twice or an edit stage without its base stage."""
    names = [s["name"] for s in stages]
    if dup := sorted({n for n in names if names.count(n) > 1}):
        raise ValueError(f"stages {dup} appear twice")
    doc = {"references": False, "launch": dict(LAUNCH if launch is None else launch), "stages": [dict(s) for s in stages]}
    pairs(doc)
    return doc


def build(
    doc: Mapping[str, Any],
    crowd: Mapping[str, Any],
    partitions: Iterable[str] = PARTITIONS,
    *,
    worlds: Path | None = None,
    robot: str = ROBOT,
    crowd_name: str = BASE_CROWD,
    regenerate: bool = True,
    dry_run: bool = False,
    log: Callable[[str], None] = print,
) -> dict[str, Any]:
    """The suite of crowd `crowd_name` of split `doc`, `crowd` its settings: the edited worlds made again, the crowd read
    into every job's world (none written on a dry run), one stage per job of that crowd. With the split's robot task the
    robot drives it in every stage and the people see it."""
    import tempfile

    from ..scenario.cli import world_root
    from .edit import open_site
    from .run import base_site, check_writable, prepare

    if regenerate and not dry_run:
        with tempfile.TemporaryDirectory(prefix="flowedit_suite_") as manifests:
            regenerate_worlds(doc, Path(manifests), log)
    duration = duration_of(doc)
    task = robot_task_of(doc)
    stages = []
    for job in jobs(doc, partitions, crowd_name):
        root = world_root(worlds, job.world)
        notes: list[str] = []
        site = open_site(root, doc["sources"][job.world].get("scenario") if is_base(job.world) else None, None, notes)
        if not dry_run:
            check_writable(worlds, job.world, root)
        prepared = prepare(site, base_site(worlds, site), [], crowd, job.seed, notes, robot=task, dry_run=dry_run)
        for note in notes:
            log(f"note: {job.label}: {note}")
        stages.append(stage(job.world, job.seed, prepared.scenario, duration, robot, task=task is not None))
    return suite_doc(stages, LAUNCH_TASK if task is not None else None)


def pairs(doc: Mapping[str, Any]) -> dict[str, str]:
    """Each edit stage of a suite `suite_doc` wrote, mapped to the base world's stage at the same seed it is scored against."""
    by_name = {s["name"] for s in doc.get("stages") or []}
    out: dict[str, str] = {}
    for s in doc.get("stages") or []:
        world, seed = parse_stage_name(s["name"])
        if not is_base(world):
            ref = stage_name(base_of(world), seed)
            if ref not in by_name:
                raise ValueError(f"{s['name']}: no stage {ref} of its base world at its seed")
            out[s["name"]] = ref
    return out


def suite_name(split: Path, crowd: str = BASE_CROWD) -> str:
    """`flowedit_<split name>`, and `__<crowd>` for a test crowd: stage names repeat across crowds, so each has its own suite."""
    return f"flowedit_{Path(split).stem}" + ("" if crowd == BASE_CROWD else f"__{crowd}")


def default_out(split: Path, crowd: str = BASE_CROWD) -> Path:
    """`<imported assets root>/suites/<suite name>.yaml`, where `arena evaluation benchmark --suite <name>` finds it."""
    from arena_simulation_setup.tree import imported_root

    return imported_root() / SUITES / f"{suite_name(split, crowd)}.yaml"


def contest_out(suite: Path) -> Path:
    """The contest file of suite file `suite`: `<root>/contests/<name>.yaml` for a suite at `<root>/suites/<name>.yaml`,
    where `--contest <name>` finds it as `--suite <name>` finds the suite; else `<name>.contest.yaml` beside the suite."""
    suite = Path(suite)
    if suite.parent.name == SUITES:
        return suite.parent.parent / CONTESTS / suite.name
    return suite.with_name(f"{suite.stem}.contest.yaml")


def contest_doc(name: str, contestants: Sequence[Mapping[str, Any]]) -> dict[str, Any]:
    """The arena_evaluation contest file of `contestants`, named `name`."""
    return {"name": name, "contestants": [dict(c) for c in contestants]}


def write(doc: Mapping[str, Any], out: Path, header: Sequence[str] = (), *, force: bool = False) -> Path:
    """Write the suite (or contest) to `out`, replacing only a file this wrote unless `force`."""
    import yaml

    out = Path(out)
    if out.is_file() and not force and not out.read_text().startswith(MARKER):
        raise ValueError(f"{out} was not written by flowedit suite, pass --force to replace it")
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join([MARKER, *(f"# {line}" for line in header)]) + "\n" + yaml.safe_dump(dict(doc), sort_keys=False))
    return out


def benchmark_command(name: str, lanes: int | None = None, contest: str = CONTEST) -> str:
    """The `arena evaluation benchmark` call that runs suite `name`."""
    return shlex.join(["arena", "evaluation", "benchmark", "--suite", name, "--contest", contest, *(["--lanes", str(lanes)] if lanes else [])])


