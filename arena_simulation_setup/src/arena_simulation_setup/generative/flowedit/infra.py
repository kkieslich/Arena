"""INFRA Stage 1 suites, the Exposé's mini H1 (study design §5, §8, §10): seed-paired arena_evaluation benchmark suites
on a site (the twin smu_link_full), with `flowedit suite`'s stage names `<world>__s<seed>`.

- `reference_suite`: the site as is without robots, one stage per seed. It runs first. Its flow cells
  (`flow_cells.parquet`) give the occupancy the joint search's fallback ranks with (`search.Occupancy.from_flow_cells`),
  and its runs are the reference each layout's element part pairs with (§6).
- `layout_suite`: each layout copy at each seed with the fleet: `fleet` task mode, 4 jackals homed on the bay slots and
  the chargers, the copy's loading point and locker. `references: true`, so the runner adds each stage's
  `unhindered_peds` run, the same copy and seed with the robots parked off the map: the layout without robots, the
  traffic part's reference. The runner also adds an `unobstructed_robot` run per stage (the fleet without pedestrians).
- `save_layouts`: each layout copy through `place.save_layout` (assets hardlinked), the crowd's scenario copied in from
  the site, so every copy has the site's source names and polygons and its pedestrians pair with the site's.

Both suites spawn the same robots with the same launch arguments, scenario and episode length, so a layout's run
without robots differs from the site's only by the elements. The warm-up (§8) is cut in the analysis, not here."""

